# Tests of scripts/license-headers.py in throw-away git repositories: header text and position for every file type,
# preambles (shebang, shellcheck directives, coding line, Dockerfile parser directive, doctype, //go:build), byte level
# details (BOM, CRLF, empty file), the file selection (untracked files, ignored files, files out of scope, symlinks),
# the exit codes of --check and --fix, idempotency, and the refusals.
#
#   ci/tests/license-headers-test.sh
#
# Needs python3 (3.9 or newer) and git. The fixtures contain the tags that the header tool looks for; they are wrapped
# in REUSE-IgnoreStart/End so that reuse does not read them as the tags of this file.
set -uo pipefail
# shellcheck source=ci/tests/lib-test.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib-test.sh"

have python3 || die "python3 not found"
have git || die "git not found"
TOOL="${ROOT}/scripts/license-headers.py"
[ -f "${TOOL}" ] || die "scripts/license-headers.py not found"
# git must not find a repository above TEST_TMP (the "not a git work tree" case)
export GIT_CEILING_DIRECTORIES="${TEST_TMP}"
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

# REUSE-IgnoreStart
C1='Copyright The Myriarch Authors'
C2='SPDX-License-Identifier: Apache-2.0'
C_OTHER_LICENSE='SPDX-License-Identifier: MIT'
C_STRAY='SPDX-License-Identifier: GPL-3.0-only'
C_YEAR='Copyright 2025 The Myriarch Authors'
# REUSE-IgnoreEnd
H_SLASH="// ${C1}\n// ${C2}\n"
H_HASH="# ${C1}\n# ${C2}\n"
H_DASH="-- ${C1}\n-- ${C2}\n"
H_CSS="/*\n * ${C1}\n * ${C2}\n */\n"
H_HTML="<!--\n  ${C1}\n  ${C2}\n-->\n"
H_HELM="{{- /*\n${C1}\n${C2}\n*/ -}}\n"

REPO=""
tool() { ( cd "${REPO}" && python3 -I "${TOOL}" "$@" ); }
put() { # path content(printf %b escapes)
  mkdir -p "$(dirname "${REPO}/$1")"
  printf '%b' "$2" > "${REPO}/$1"
}
new_repo() { # name
  REPO="${TEST_TMP}/$1"
  mkdir -p "${REPO}"
  git -C "${REPO}" init -q
}
# same <name> <path> <expected content (printf %b escapes)>: the file has exactly that content
same() {
  printf '%b' "$3" > "${TEST_TMP}/expected"
  if cmp -s "${TEST_TMP}/expected" "${REPO}/$2"; then
    ok "$1"
  else
    fail "$1 (content of $2 differs)"
    diff -u "${TEST_TMP}/expected" "${REPO}/$2" | od -c | head -n 20 | sed 's/^/        /' >&2
  fi
}
# rc_is <name> <expected exit status> <message regex or ''> <command...>
rc_is() {
  local name="$1" want="$2" re="$3" rc=0; shift 3
  OUT="$("$@" 2>&1)" || rc=$?
  if [ "${rc}" != "${want}" ]; then
    fail "${name} (exit ${rc}, expected ${want})"; printf '%s\n' "${OUT}" | sed 's/^/        /' >&2
  elif [ -n "${re}" ] && ! printf '%s' "${OUT}" | grep -Eq -- "${re}"; then
    fail "${name} (message does not match /${re}/)"; printf '%s\n' "${OUT}" | sed 's/^/        /' >&2
  else
    ok "${name}"
  fi
}
tree_sum() { ( cd "${REPO}" && find . -path ./.git -prune -o -type f -print | LC_ALL=C sort | while IFS= read -r f; do cksum "${f}"; done ); }

# ---- repository 1: everything --fix can fix -------------------------------------------------------------------
new_repo fixable
printf 'ignored/\n*.out\n' > "${REPO}/.gitignore"

put go/build.go '//go:build linux\n\n// Package build does things.\npackage build\n'
put go/generated.go '// Code generated by tool. DO NOT EDIT.\n\npackage gen\n'
put go/doc.go '// Package doc has a doc comment on the first line.\npackage doc\n'
put go/api.d.ts 'export declare const x: number\n'
put web/cli.ts '#!/usr/bin/env node\nconsole.log(1)\n'
put web/app.tsx 'export const App = () => null\n'
put web/run.mjs 'import x from "y"\n'
put web/run.cjs 'module.exports = {}\n'
put web/run.js 'export default {}\n'
put sh/shebang.sh '#!/usr/bin/env bash\n# shellcheck disable=SC2034\n# shellcheck source=lib.sh\n# Usage: shebang.sh\nset -e\n'
put sh/plain.sh '#!/bin/sh\n\n# Description\nset -e\n'
put sh/nobang.sh '# shellcheck shell=sh\nfoo=1\n'
put sh/lib.bash 'foo() { :; }\n'
put py/tool.py '#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n"""Doc."""\n'
put py/coding.py '# vim: set fileencoding=utf-8 :\nx = 1\n'
put py/plain.py '"""Doc."""\nx = 1\n'
put win/install.ps1 '#Requires -Version 5.1\n<#\n.SYNOPSIS\nx\n#>\nparam()\n'
put db/00001.sql 'SELECT 1;\n'
put web/theme.css 'body { margin: 0 }\n'
put web/index.html '<!doctype html>\n<html></html>\n'
put web/upper.html '<!DOCTYPE html>\n<html></html>\n'
put web/nodoctype.html '<html></html>\n'
put deploy/Dockerfile '# syntax=docker/dockerfile:1.7\nFROM scratch\n'
put deploy/app.Dockerfile 'FROM scratch\n'
put deploy/two.Dockerfile '# syntax=docker/dockerfile:1.7\n# escape=\\\nFROM scratch\n'
put Makefile 'all:\n\ttrue\n'
put deploy/x.service '[Unit]\nDescription=x\n'
put scripts/e2e/ui-updates/a.yaml.tmpl 'key: @@X@@\n'
put deploy/helm/c/templates/cm.yaml 'apiVersion: v1\nkind: ConfigMap\n'
put deploy/helm/c/templates/_helpers.tpl '{{- define "c.name" -}}c{{- end -}}\n'
put deploy/helm/c/templates/NOTES.txt 'Installed.\n'
put website/layouts/baseof.html '<!doctype html>\n<html></html>\n'
put website/layouts/_partials/repo/x.html '{{ define "x" }}x{{ end }}\n'
put website/layouts/robots.txt 'User-agent: *\n'
put website/layouts/sitemap.xml '<urlset></urlset>\n'
put website/content/docs/adr/_content.gotmpl '{{ range resources.Match "x" }}{{ end }}\n'
put website/content/page.gotmpl 'not a content adapter\n'
put website/assets/scss/_styles.scss '.a { b: c }\n'
put website/static/site.webmanifest '{}\n'
put bom/b.go '\xef\xbb\xbfpackage b\n'
put crlf/c.go 'package c\r\n\r\nfunc f() {}\r\n'
put empty/e.go ''
put nonl/n.sh '#!/bin/sh\necho hi'
put onlyshebang/s.sh '#!/bin/sh\n'
put already/ok.go "${H_SLASH}\npackage ok\n"
# out of scope or not to be touched
put ignored/x.go 'package ignored\n'
put build.out '#!/bin/sh\n'
put docs/notes.md '# Notes\n'
put data/values.json '{}\n'
put deploy/x.Dockerfile.dockerignore '*\n'
put scripts/noext 'echo\n'
ln -s go/build.go "${REPO}/link.go"

expect_ok "list: succeeds" tool --list
LIST="$(tool --list)"
for f in go/build.go sh/shebang.sh deploy/helm/c/templates/NOTES.txt scripts/e2e/ui-updates/a.yaml.tmpl Makefile deploy/app.Dockerfile; do
  if printf '%s\n' "${LIST}" | grep -Fq -- "	${f}"; then ok "list: ${f} is in scope"; else fail "list: ${f} is missing"; fi
done
for f in website/content/page.gotmpl website/static/site.webmanifest; do
  if printf '%s\n' "${LIST}" | grep -Fq -- "	${f}"; then fail "list: ${f} must not be in scope"; else ok "list: ${f} is not in scope"; fi
done
for f in ignored/x.go build.out docs/notes.md data/values.json deploy/x.Dockerfile.dockerignore scripts/noext link.go .gitignore; do
  if printf '%s\n' "${LIST}" | grep -Fq -- "	${f}"; then fail "list: ${f} must not be in scope"; else ok "list: ${f} is not in scope"; fi
done
if printf '%s\n' "${LIST}" | grep -Fxq "go	go/build.go" && printf '%s\n' "${LIST}" | grep -Fxq "helm	deploy/helm/c/templates/cm.yaml"; then
  ok "list: format is style<TAB>path"
else
  fail "list: format is not style<TAB>path"
fi

rc_is "check: files without a header are reported (exit 1)" 1 'go/build.go: missing' tool --check
rc_is "check: summary line" 1 'license-headers: [0-9]+ of [0-9]+ files need attention' tool --check
rc_is "check: an exact header is not reported" 0 'all headers ok' tool --check already/ok.go
BEFORE_IGNORED="$(cksum "${REPO}/ignored/x.go")"

FIXED="$(tool --fix 2>"${TEST_TMP}/fix.err")"; RC=$?
if [ "${RC}" = 0 ]; then ok "fix: exit 0"; else fail "fix: exit ${RC}"; cat "${TEST_TMP}/fix.err" >&2; fi
if printf '%s\n' "${FIXED}" | grep -Fxq 'go/build.go' && ! printf '%s\n' "${FIXED}" | grep -Fxq 'already/ok.go'; then
  ok "fix: prints the changed paths, not the files that were fine"
else
  fail "fix: output is wrong"; printf '%s\n' "${FIXED}" | sed 's/^/        /' >&2
fi
if [ "$(printf '%s\n' "${FIXED}" | LC_ALL=C sort)" = "${FIXED}" ]; then ok "fix: output is sorted"; else fail "fix: output is not sorted"; fi

same "go: //go:build and package doc stay after the header" go/build.go "${H_SLASH}\n//go:build linux\n\n// Package build does things.\npackage build\n"
same "go: Code generated line comes after the header" go/generated.go "${H_SLASH}\n// Code generated by tool. DO NOT EDIT.\n\npackage gen\n"
same "go: package doc on the first line is separated by an empty line" go/doc.go "${H_SLASH}\n// Package doc has a doc comment on the first line.\npackage doc\n"
same "d.ts" go/api.d.ts "${H_SLASH}\nexport declare const x: number\n"
same "ts: shebang stays first" web/cli.ts "#!/usr/bin/env node\n${H_SLASH}\nconsole.log(1)\n"
same "tsx" web/app.tsx "${H_SLASH}\nexport const App = () => null\n"
same "mjs" web/run.mjs "${H_SLASH}\nimport x from \"y\"\n"
same "cjs" web/run.cjs "${H_SLASH}\nmodule.exports = {}\n"
same "js" web/run.js "${H_SLASH}\nexport default {}\n"
same "sh: shebang and shellcheck directives stay first" sh/shebang.sh "#!/usr/bin/env bash\n# shellcheck disable=SC2034\n# shellcheck source=lib.sh\n${H_HASH}\n# Usage: shebang.sh\nset -e\n"
same "sh: an empty line after the shebang is not doubled" sh/plain.sh "#!/bin/sh\n${H_HASH}\n# Description\nset -e\n"
same "sh: no shebang, shellcheck directive stays first" sh/nobang.sh "# shellcheck shell=sh\n${H_HASH}\nfoo=1\n"
same "bash" sh/lib.bash "${H_HASH}\nfoo() { :; }\n"
same "py: shebang and coding line stay first" py/tool.py "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n${H_HASH}\n\"\"\"Doc.\"\"\"\n"
same "py: coding line on line 1 stays first" py/coding.py "# vim: set fileencoding=utf-8 :\n${H_HASH}\nx = 1\n"
same "py: plain" py/plain.py "${H_HASH}\n\"\"\"Doc.\"\"\"\nx = 1\n"
same "ps1: header above #Requires" win/install.ps1 "${H_HASH}\n#Requires -Version 5.1\n<#\n.SYNOPSIS\nx\n#>\nparam()\n"
same "sql" db/00001.sql "${H_DASH}\nSELECT 1;\n"
same "css" web/theme.css "${H_CSS}\nbody { margin: 0 }\n"
same "html: doctype stays first, no empty line after the header" web/index.html "<!doctype html>\n${H_HTML}<html></html>\n"
same "html: upper case doctype" web/upper.html "<!DOCTYPE html>\n${H_HTML}<html></html>\n"
same "html: without a doctype" web/nodoctype.html "${H_HTML}<html></html>\n"
same "Dockerfile: parser directive stays on line 1" deploy/Dockerfile "# syntax=docker/dockerfile:1.7\n${H_HASH}\nFROM scratch\n"
same "*.Dockerfile without a directive" deploy/app.Dockerfile "${H_HASH}\nFROM scratch\n"
same "*.Dockerfile with two directives" deploy/two.Dockerfile "# syntax=docker/dockerfile:1.7\n# escape=\\\\\n${H_HASH}\nFROM scratch\n"
same "Makefile" Makefile "${H_HASH}\nall:\n\ttrue\n"
same "service" deploy/x.service "${H_HASH}\n[Unit]\nDescription=x\n"
same "tmpl" scripts/e2e/ui-updates/a.yaml.tmpl "${H_HASH}\nkey: @@X@@\n"
same "helm: yaml, no empty line after the header" deploy/helm/c/templates/cm.yaml "${H_HELM}apiVersion: v1\nkind: ConfigMap\n"
same "helm: tpl" deploy/helm/c/templates/_helpers.tpl "${H_HELM}{{- define \"c.name\" -}}c{{- end -}}\n"
same "helm: NOTES.txt" deploy/helm/c/templates/NOTES.txt "${H_HELM}Installed.\n"
same "hugo: layout html, header is a template comment, doctype is not a preamble" website/layouts/baseof.html "${H_HELM}<!doctype html>\n<html></html>\n"
same "hugo: partial" website/layouts/_partials/repo/x.html "${H_HELM}{{ define \"x\" }}x{{ end }}\n"
same "hugo: robots.txt" website/layouts/robots.txt "${H_HELM}User-agent: *\n"
same "hugo: xml" website/layouts/sitemap.xml "${H_HELM}<urlset></urlset>\n"
same "hugo: content adapter" website/content/docs/adr/_content.gotmpl "${H_HELM}{{ range resources.Match \"x\" }}{{ end }}\n"
same "scss uses the CSS block comment" website/assets/scss/_styles.scss "${H_CSS}\n.a { b: c }\n"
same "hugo: content that is not an adapter is untouched" website/content/page.gotmpl 'not a content adapter\n'
same "hugo: a webmanifest is covered by REUSE.toml, not touched" website/static/site.webmanifest '{}\n'
same "BOM stays first" bom/b.go "\xef\xbb\xbf${H_SLASH}\npackage b\n"
same "CRLF is kept" crlf/c.go "// ${C1}\r\n// ${C2}\r\n\r\npackage c\r\n\r\nfunc f() {}\r\n"
same "empty file: the header is the whole file" empty/e.go "${H_SLASH}"
same "no newline at the end of the file is kept" nonl/n.sh "#!/bin/sh\n${H_HASH}\necho hi"
same "a file with only a shebang: the header ends with a newline" onlyshebang/s.sh "#!/bin/sh\n${H_HASH}"
same "an exact header is not touched" already/ok.go "${H_SLASH}\npackage ok\n"
same "untracked, not ignored file is fixed" go/doc.go "${H_SLASH}\n// Package doc has a doc comment on the first line.\npackage doc\n"
same "ignored file is untouched" ignored/x.go 'package ignored\n'
same "ignored file with a shebang is untouched" build.out '#!/bin/sh\n'
same "out of scope: Markdown" docs/notes.md '# Notes\n'
same "out of scope: JSON" data/values.json '{}\n'
same "out of scope: dockerignore" deploy/x.Dockerfile.dockerignore '*\n'
same "out of scope: file without extension" scripts/noext 'echo\n'
same "symlink is skipped" go/build.go "${H_SLASH}\n//go:build linux\n\n// Package build does things.\npackage build\n"
if [ "$(cksum "${REPO}/ignored/x.go")" = "${BEFORE_IGNORED}" ]; then ok "ignored file: checksum unchanged"; else fail "ignored file changed"; fi
if [ -L "${REPO}/link.go" ] && [ "$(readlink "${REPO}/link.go")" = "go/build.go" ]; then ok "symlink is still a symlink"; else fail "symlink was replaced"; fi

SUM1="$(tree_sum)"
SECOND="$(tool --fix 2>&1)"; RC=$?
if [ "${RC}" = 0 ] && ! printf '%s\n' "${SECOND}" | grep -Eq '^[A-Za-z0-9_./-]+$'; then ok "fix is idempotent: the second run prints no path"; else fail "second fix run printed paths (exit ${RC})"; printf '%s\n' "${SECOND}" | sed 's/^/        /' >&2; fi
if [ "$(tree_sum)" = "${SUM1}" ]; then ok "fix is idempotent: the second run changes nothing"; else fail "second fix run changed files"; fi
rc_is "check passes after fix" 0 'all headers ok' tool --check

# narrowing to PATH arguments
new_repo narrow
put a/x.go 'package x\n'
put b/y.go 'package y\n'
rc_is "check PATH: only the given directory (clean directory)" 1 'a/x.go: missing' tool --check a
rc_is "check PATH: the other directory is not reported" 1 '1 of 1 files' tool --check a
rc_is "check PATH: a file" 1 'b/y.go: missing' tool --check b/y.go
tool --fix a >/dev/null 2>&1
same "fix PATH: only the given directory is changed" a/x.go "${H_SLASH}\npackage x\n"
same "fix PATH: the other directory is untouched" b/y.go 'package y\n'
rc_is "check PATH outside the repository: usage error" 2 'outside the repository' tool --check /
rc_is "check PATH that does not exist: usage error" 2 'PATH does not exist: nonexist' tool --check nonexist
rc_is "fix PATH that does not exist: usage error" 2 'PATH does not exist: a/nonexist.go' tool --fix a/nonexist.go
rc_is "list PATH that does not exist: usage error" 2 'PATH does not exist' tool --list nonexist
if ( cd "${REPO}/a" && python3 -I "${TOOL}" --check x.go >"${TEST_TMP}/sub.out" 2>&1 ); then
  ok "check from a subdirectory with a relative PATH"
else
  fail "check from a subdirectory"; cat "${TEST_TMP}/sub.out" >&2
fi

# ---- repository 2: reasons of --check, refusals of --fix ----------------------------------------------------------
new_repo bad
put missing.go 'package m\n'
put wrongtext.go "// ${C1}\n// ${C_OTHER_LICENSE}\n\npackage w\n"
put wrongyear.go "// ${C_YEAR}\n// ${C2}\n\npackage w\n"
put wrongpos.go "package p\n\n// ${C1}\n// ${C2}\n"
put afterbang.sh "# a comment\n#!/bin/sh\n${H_HASH}"
# the header on line 0 hides a preamble line below it: the preamble would be ignored (Docker, the kernel, Python, browsers)
put misplaced-docker.Dockerfile "${H_HASH}\n# syntax=docker/dockerfile:1.7\nFROM scratch\n"
put misplaced-shebang.sh "${H_HASH}\n#!/usr/bin/env bash\nset -e\n"
put misplaced-python.py "${H_HASH}\n#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n"
put misplaced-coding.py "${H_HASH}\n# -*- coding: latin-1 -*-\nx = 1\n"
put misplaced-html.html "${H_HTML}<!doctype html>\n<html></html>\n"
put misplaced-ts.ts "${H_SLASH}\n#!/usr/bin/env node\nconsole.log(1)\n"
# a shellcheck directive after the header is fine; the header at its position with the content after it is fine
put goodshellcheck.sh "#!/bin/sh\n${H_HASH}\n# shellcheck disable=SC2034\nset -e\n"
put gooddocker.Dockerfile "# syntax=docker/dockerfile:1.7\n${H_HASH}\nFROM scratch\n"
put stray.sh "#!/bin/sh\n# ${C_STRAY}\necho x\n"
put copyrightonly.py "# ${C1}\nx = 1\n"
put noblank.go "${H_SLASH}package nb\n"
put deploy/helm/c/templates/ws.yaml '  indented: true\n'
put deploy/helm/c/templates/blank.yaml '\nkind: X\n'
put deploy/helm/c/templates/ok.yaml 'kind: X\n'
put website/layouts/_partials/ws.html '  {{ "x" }}\n'
put website/layouts/_partials/blank.html '\n{{ "x" }}\n'
put website/layouts/_partials/stray.html "{{ \"x\" }}\n{{/* ${C_STRAY} */}}\n"
put website/layouts/_partials/good.html "{{- /*\n${C1}\n${C2}\n*/ -}}\n{{ \"x\" }}\n"
put website/layouts/_partials/pos.html "{{ \"x\" }}\n{{- /*\n${C1}\n${C2}\n*/ -}}\n"
rc_is "check: missing" 1 'missing\.go: missing' tool --check
rc_is "check: wrong text (other license)" 1 'wrongtext\.go: wrong text' tool --check
rc_is "check: wrong text (year in the copyright line)" 1 'wrongyear\.go: wrong text' tool --check
rc_is "check: wrong position" 1 'wrongpos\.go: wrong position' tool --check
rc_is "check: header after a comment line before the shebang is in the wrong position" 1 'afterbang\.sh: wrong position' tool --check
for f in misplaced-docker.Dockerfile misplaced-shebang.sh misplaced-python.py misplaced-coding.py misplaced-html.html misplaced-ts.ts; do
  rc_is "check: header above a preamble line (${f}) is in the wrong position" 1 "${f//./\\.}: wrong position" tool --check
done
if tool --check 2>&1 | grep -Eq '^(goodshellcheck\.sh|gooddocker\.Dockerfile):'; then fail "check: a correct header with a following shellcheck directive or a leading Docker directive is reported"; else ok "check: correct headers next to preamble lines pass"; fi
rc_is "check: a stray SPDX tag is wrong text" 1 'stray\.sh: wrong text' tool --check
rc_is "check: a copyright line without the license tag is wrong text" 1 'copyrightonly\.py: wrong text' tool --check
rc_is "check: no empty line after the header is wrong text or missing" 1 'noblank\.go: (wrong text|missing|wrong position)' tool --check
rc_is "check: Helm template starting with whitespace is refused" 1 'ws\.yaml: refused' tool --check
rc_is "check: Helm template starting with an empty line is refused" 1 'blank\.yaml: refused' tool --check
rc_is "check: Hugo template starting with whitespace is refused" 1 '_partials/ws\.html: refused' tool --check
rc_is "check: Hugo template starting with an empty line is refused" 1 '_partials/blank\.html: refused' tool --check
rc_is "check: Hugo template with a stray tag is wrong text" 1 '_partials/stray\.html: wrong text' tool --check
rc_is "check: Hugo template with the header in the wrong position" 1 '_partials/pos\.html: wrong position' tool --check
if tool --check 2>&1 | grep -Eq '_partials/good\.html:'; then fail "check: a correct Hugo header is reported"; else ok "check: a correct Hugo header passes"; fi
CHK="$(tool --check 2>&1)"
if [ "$(printf '%s\n' "${CHK}" | grep -v '^license-headers:' | LC_ALL=C sort)" = "$(printf '%s\n' "${CHK}" | grep -v '^license-headers:')" ]; then ok "check: findings are sorted"; else fail "check: findings are not sorted"; fi
if printf '%s' "${CHK}" | grep -q "${TEST_TMP}"; then fail "check: output contains an absolute path"; else ok "check: output has no absolute path"; fi
SUM2="$(tree_sum)"
rc_is "fix: refuses and exits 1" 1 'manual fix' tool --fix
same "fix: inserts the header into the file that only lacks it" missing.go "${H_SLASH}\npackage m\n"
same "fix: refused file with another license is unchanged" wrongtext.go "// ${C1}\n// ${C_OTHER_LICENSE}\n\npackage w\n"
same "fix: refused file with the header in the wrong position is unchanged" wrongpos.go "package p\n\n// ${C1}\n// ${C2}\n"
same "fix: refused stray tag is unchanged" stray.sh "#!/bin/sh\n# ${C_STRAY}\necho x\n"
same "fix: refused Helm template with whitespace is unchanged" deploy/helm/c/templates/ws.yaml '  indented: true\n'
same "fix: refused Helm template with an empty first line is unchanged" deploy/helm/c/templates/blank.yaml '\nkind: X\n'
same "fix: refused Hugo template with whitespace is unchanged" website/layouts/_partials/ws.html '  {{ "x" }}\n'
same "fix: refused Hugo template with a stray tag is unchanged" website/layouts/_partials/stray.html "{{ \"x\" }}\n{{/* ${C_STRAY} */}}\n"
same "fix: Helm template that can be fixed" deploy/helm/c/templates/ok.yaml "${H_HELM}kind: X\n"
if [ "$(tree_sum)" != "${SUM2}" ]; then ok "fix: changed the fixable file"; else fail "fix: changed nothing"; fi
rc_is "fix: the refusal names the file" 1 'stray\.sh: refused, manual fix' tool --fix

# ---- usage and environment ---------------------------------------------------------------------------------------
mkdir -p "${TEST_TMP}/nogit"
rc_is "outside a git work tree: exit 2" 2 'not a git work tree' bash -c "cd '${TEST_TMP}/nogit' && python3 -I '${TOOL}' --check"
rc_is "no mode: exit 2" 2 'usage:' python3 -I "${TOOL}"
rc_is "unknown mode: exit 2" 2 'usage:' python3 -I "${TOOL}" --frobnicate
rc_is "unknown option: exit 2" 2 'usage:' python3 -I "${TOOL}" --check --bogus
rc_is "the tool passes its own check" 0 'all headers ok' bash -c "cd '${ROOT}' && python3 -I scripts/license-headers.py --check scripts/license-headers.py"

finish_tests "license-headers-test"
