// Package apidoc renders the REST API reference (docs/reference/api) from the OpenAPI 3.1 contract api/openapi.yaml.
//
// The generator is deliberately small. Load reads the subset of OpenAPI that the contract uses into a minimal model and
// Validate rejects everything outside that subset (allOf, oneOf, anyOf, not, discriminator, type arrays, inline nested
// objects, external references, multi-paragraph property descriptions, ...), naming the JSON pointer of the offending node.
// A future change of the contract therefore extends the generator explicitly and is never dropped silently. Render writes one
// page per tag, a page with the data types and an index; the result is deterministic.
//
// The files are generated by "make docs-gen" (APIDOC_UPDATE=1 go test -run TestAPIReference ./internal/apidoc) and guarded
// against drift by the same test without the variable (internal/docgen writes and compares the files). The package does not
// import the authorization code: Options.RoleFor maps a permission to the lowest role that holds it, and the test feeds it
// from internal/authz, so the permission tables cannot drift from the code.
package apidoc

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// OMap is a YAML mapping that keeps the order of its keys.
type OMap[T any] struct {
	Keys   []string
	Values map[string]T
}

// UnmarshalYAML implements yaml.Unmarshaler.
func (m *OMap[T]) UnmarshalYAML(n *yaml.Node) error {
	if n.Kind != yaml.MappingNode {
		return fmt.Errorf("line %d: a mapping is expected", n.Line)
	}
	m.Keys = nil
	m.Values = make(map[string]T, len(n.Content)/2)
	for i := 0; i+1 < len(n.Content); i += 2 {
		key := n.Content[i].Value
		var v T
		if err := n.Content[i+1].Decode(&v); err != nil {
			return err
		}
		if _, dup := m.Values[key]; dup {
			return fmt.Errorf("line %d: duplicate key %q", n.Content[i].Line, key)
		}
		m.Keys = append(m.Keys, key)
		m.Values[key] = v
	}
	return nil
}

// Get returns the value of key.
func (m OMap[T]) Get(key string) (T, bool) {
	v, ok := m.Values[key]
	return v, ok
}

// Spec is the part of an OpenAPI document that the generator reads.
type Spec struct {
	OpenAPI  string
	Info     Info
	Servers  []Server
	Security []map[string][]string
	Tags     []Tag
	// Operations of all paths in the order of the document (paths in YAML order, the methods of a path in YAML order).
	Operations []*Operation

	Schemas         OMap[*Schema]
	Parameters      OMap[*Parameter]
	Responses       OMap[*Response]
	SecuritySchemes OMap[*SecurityScheme]
}

// Info is the info object.
type Info struct {
	Title       string `yaml:"title"`
	Version     string `yaml:"version"`
	Summary     string `yaml:"summary"`
	Description string `yaml:"description"`
	Contact     struct {
		Name  string `yaml:"name"`
		URL   string `yaml:"url"`
		Email string `yaml:"email"`
	} `yaml:"contact"`
	License struct {
		Name       string `yaml:"name"`
		Identifier string `yaml:"identifier"`
		URL        string `yaml:"url"`
	} `yaml:"license"`
}

// Server is a server object.
type Server struct {
	URL         string `yaml:"url"`
	Description string `yaml:"description"`
}

// Tag is a tag object.
type Tag struct {
	Name        string `yaml:"name"`
	Description string `yaml:"description"`
}

// SecurityScheme is a security scheme object.
type SecurityScheme struct {
	Type        string `yaml:"type"`
	In          string `yaml:"in"`
	Name        string `yaml:"name"`
	Scheme      string `yaml:"scheme"`
	Description string `yaml:"description"`
}

// Operation is an operation with the parameters of its path item.
type Operation struct {
	Method      string
	Path        string
	OperationID string `yaml:"operationId"`
	Tags        []string
	Summary     string
	Description string
	// Security is nil when the operation inherits the global requirement and points to an empty slice for "security: []".
	Security    *[]map[string][]string `yaml:"security"`
	Permission  string                 `yaml:"x-permission"`
	Parameters  []*Parameter
	RequestBody *RequestBody `yaml:"requestBody"`
	Responses   OMap[*Response]
}

// Parameter is a parameter object or a reference to one.
type Parameter struct {
	Ref         string  `yaml:"$ref"`
	Name        string  `yaml:"name"`
	In          string  `yaml:"in"`
	Description string  `yaml:"description"`
	Required    bool    `yaml:"required"`
	Style       string  `yaml:"style"`
	Explode     *bool   `yaml:"explode"`
	Schema      *Schema `yaml:"schema"`
}

// RequestBody is a request body object.
type RequestBody struct {
	Description string           `yaml:"description"`
	Required    bool             `yaml:"required"`
	Content     OMap[*MediaType] `yaml:"content"`
}

// Response is a response object or a reference to one.
type Response struct {
	Ref         string           `yaml:"$ref"`
	Description string           `yaml:"description"`
	Content     OMap[*MediaType] `yaml:"content"`
}

// MediaType is a media type object.
type MediaType struct {
	Schema *Schema `yaml:"schema"`
}

// AdditionalProps is the value of additionalProperties: a boolean or a schema.
type AdditionalProps struct {
	Allowed bool
	Schema  *Schema
}

// UnmarshalYAML implements yaml.Unmarshaler.
func (a *AdditionalProps) UnmarshalYAML(n *yaml.Node) error {
	if n.Kind == yaml.ScalarNode {
		return n.Decode(&a.Allowed)
	}
	a.Allowed = true
	return n.Decode(&a.Schema)
}

// Schema is a schema object (the allowlisted keywords only, see Validate).
type Schema struct {
	Ref                  string           `yaml:"$ref"`
	Type                 string           `yaml:"type"`
	Format               string           `yaml:"format"`
	Description          string           `yaml:"description"`
	Enum                 []any            `yaml:"enum"`
	Default              any              `yaml:"default"`
	Example              any              `yaml:"example"`
	Properties           OMap[*Schema]    `yaml:"properties"`
	Required             []string         `yaml:"required"`
	Items                *Schema          `yaml:"items"`
	AdditionalProperties *AdditionalProps `yaml:"additionalProperties"`
	Minimum              *float64         `yaml:"minimum"`
	Maximum              *float64         `yaml:"maximum"`
	MinLength            *int             `yaml:"minLength"`
	MaxLength            *int             `yaml:"maxLength"`
	MinItems             *int             `yaml:"minItems"`
	MaxItems             *int             `yaml:"maxItems"`
	UniqueItems          bool             `yaml:"uniqueItems"`
	Pattern              string           `yaml:"pattern"`
	Deprecated           bool             `yaml:"deprecated"`
	ReadOnly             bool             `yaml:"readOnly"`
	WriteOnly            bool             `yaml:"writeOnly"`
}

// pathItem is a path item in the order of its keys.
type pathItem struct {
	Parameters []*Parameter
	Methods    []string
	Ops        map[string]*Operation
}

func (p *pathItem) UnmarshalYAML(n *yaml.Node) error {
	if n.Kind != yaml.MappingNode {
		return fmt.Errorf("line %d: a mapping is expected", n.Line)
	}
	p.Ops = map[string]*Operation{}
	for i := 0; i+1 < len(n.Content); i += 2 {
		key, val := n.Content[i].Value, n.Content[i+1]
		if key == "parameters" {
			if err := val.Decode(&p.Parameters); err != nil {
				return err
			}
			continue
		}
		var op Operation
		if err := val.Decode(&op); err != nil {
			return err
		}
		p.Methods = append(p.Methods, key)
		p.Ops[key] = &op
	}
	return nil
}

type rawSpec struct {
	OpenAPI    string                `yaml:"openapi"`
	Info       Info                  `yaml:"info"`
	Servers    []Server              `yaml:"servers"`
	Security   []map[string][]string `yaml:"security"`
	Tags       []Tag                 `yaml:"tags"`
	Paths      OMap[*pathItem]       `yaml:"paths"`
	Components struct {
		Schemas         OMap[*Schema]         `yaml:"schemas"`
		Parameters      OMap[*Parameter]      `yaml:"parameters"`
		Responses       OMap[*Response]       `yaml:"responses"`
		SecuritySchemes OMap[*SecurityScheme] `yaml:"securitySchemes"`
	} `yaml:"components"`
}

// Load validates the document (see Validate) and reads it into the model.
func Load(spec []byte) (*Spec, error) {
	if err := Validate(spec); err != nil {
		return nil, err
	}
	var raw rawSpec
	if err := yaml.Unmarshal(spec, &raw); err != nil {
		return nil, fmt.Errorf("apidoc: %w", err)
	}
	s := &Spec{
		OpenAPI: raw.OpenAPI, Info: raw.Info, Servers: raw.Servers, Security: raw.Security, Tags: raw.Tags,
		Schemas: raw.Components.Schemas, Parameters: raw.Components.Parameters, Responses: raw.Components.Responses,
		SecuritySchemes: raw.Components.SecuritySchemes,
	}
	for _, path := range raw.Paths.Keys {
		item := raw.Paths.Values[path]
		for _, m := range item.Methods {
			op := item.Ops[m]
			op.Method = strings.ToUpper(m)
			op.Path = path
			op.Parameters = append(append([]*Parameter{}, item.Parameters...), op.Parameters...)
			s.Operations = append(s.Operations, op)
		}
	}
	return s, nil
}

// refName returns the name of a local reference of the given kind ("schemas", "parameters" or "responses").
func refName(ref, kind string) (string, bool) {
	prefix := "#/components/" + kind + "/"
	if !strings.HasPrefix(ref, prefix) || len(ref) == len(prefix) || strings.Contains(ref[len(prefix):], "/") {
		return "", false
	}
	return ref[len(prefix):], true
}

// Schema resolves a schema reference to the name and the schema of the component.
func (s *Spec) schemaRef(ref string) (string, *Schema, error) {
	name, ok := refName(ref, "schemas")
	if !ok {
		return "", nil, fmt.Errorf("apidoc: unsupported schema reference %q", ref)
	}
	sc, ok := s.Schemas.Get(name)
	if !ok {
		return "", nil, fmt.Errorf("apidoc: schema reference %q does not resolve", ref)
	}
	return name, sc, nil
}

// parameter resolves a parameter reference.
func (s *Spec) parameter(p *Parameter) (*Parameter, error) {
	if p.Ref == "" {
		return p, nil
	}
	name, ok := refName(p.Ref, "parameters")
	if !ok {
		return nil, fmt.Errorf("apidoc: unsupported parameter reference %q", p.Ref)
	}
	r, ok := s.Parameters.Get(name)
	if !ok {
		return nil, fmt.Errorf("apidoc: parameter reference %q does not resolve", p.Ref)
	}
	return r, nil
}

// response resolves a response reference; the name is empty for an inline response.
func (s *Spec) response(r *Response) (string, *Response, error) {
	if r.Ref == "" {
		return "", r, nil
	}
	name, ok := refName(r.Ref, "responses")
	if !ok {
		return "", nil, fmt.Errorf("apidoc: unsupported response reference %q", r.Ref)
	}
	c, ok := s.Responses.Get(name)
	if !ok {
		return "", nil, fmt.Errorf("apidoc: response reference %q does not resolve", r.Ref)
	}
	return name, c, nil
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// problems collects validation findings.
type problems []string

func (p *problems) add(ptr, format string, args ...any) {
	*p = append(*p, ptr+": "+fmt.Sprintf(format, args...))
}

func (p problems) err() error {
	if len(p) == 0 {
		return nil
	}
	return errors.New("apidoc: the contract uses features the generator does not render:\n  " + strings.Join(p, "\n  "))
}

func ptrJoin(ptr string, parts ...string) string {
	var b bytes.Buffer
	b.WriteString(ptr)
	for _, p := range parts {
		b.WriteByte('/')
		b.WriteString(strings.NewReplacer("~", "~0", "/", "~1").Replace(p))
	}
	return b.String()
}
