// ChartSchemaFile is the name of the generated values schema in the chart directory.
const ChartSchemaFile = "values.schema.json"

// chartConfigMarker is the key of the placeholder that the generator replaces by the configuration subtree.
const chartConfigMarker = "x-generated"

// durationPattern matches the strings that time.ParseDuration accepts. A YAML integer is refused by the loader (it has no unit),
// and a ${VAR} reference is expanded only after the duration is decoded, so a duration setting is exactly such a string.
const durationPattern = `^[-+]?(0|(([0-9]+(\.[0-9]*)?|\.[0-9]+)(ns|us|ms|s|m|h))+)$`

// ChartSchemaSource is everything RenderChartValuesSchema needs.
type ChartSchemaSource struct {
	// Source is the hand-written part of the schema: a JSON Schema written as YAML. The property config of its root object holds
	// the placeholder "x-generated: <Config.Origin>", which the generator replaces by the configuration subtree.
	Source []byte
	// SourceName is the path of the source file in the repository; the comment of the generated file names it.
	SourceName string
	// Config describes the configuration subtree. A chart without a generated block leaves Config.Root nil; its source then has no
	// placeholder and is converted to JSON as it is.
	Config ChartConfigSource
}

// ChartConfigSource describes the subtree of the schema for the configuration file of the server.
type ChartConfigSource struct {
	// Root is the type of the configuration structure; its YAML keys are the properties of the subtree.
	Root reflect.Type
	// Origin names where the subtree comes from, for example "internal/config". The placeholder of the source and the comment of
	// the generated file name it.
	Origin string
	// SourceFiles are the Go files with the declarations of the structure; their doc comments are the descriptions.
	SourceFiles []string
	// Description introduces the subtree. A sentence that lists the excluded keys is appended.
	Description string
	// Excluded lists the keys that the chart does not offer although the structure has them.
	Excluded []ChartExclusion
}

// ChartExclusion is a key of the configuration that the schema leaves out.
type ChartExclusion struct {
	// Path is the dotted YAML path in the notation of the configuration reference: "database.dsn", "notifications.channels[].url"
	// for a field of the entries of a list and "executors.secrets.<name>.env" for a field of the entries of a map.
	Path string
	// Reason says in one phrase why the chart does not offer the key; it becomes part of the description.
	Reason string
}

// RenderChartValuesSchema assembles the values schema of a Helm chart: the hand-written source with its placeholder replaced by
// the subtree that is derived from the configuration structure. The result is JSON with the keys in the order of the source and
// of the structure, so a change of either shows as a small diff.
func RenderChartValuesSchema(src ChartSchemaSource) ([]byte, error) {
	tree, err := parseSchemaSource(src.SourceName, src.Source)
	if err != nil {
		return nil, err
	}
	comment := fmt.Sprintf("Generated by `make docs-gen` from %s. Do not edit this file by hand: change the source and run `make docs-gen`.", src.SourceName)
	if src.Config.Root != nil {
		sub, err := src.Config.subtree()
		if err != nil {
			return nil, err
		}
		if err := replaceConfigMarker(tree, src.SourceName, src.Config.Origin, sub); err != nil {
			return nil, err
		}
		comment = fmt.Sprintf("Generated by `make docs-gen` from %s and %s. Do not edit this file by hand: change the source or the configuration structure and run `make docs-gen`.", src.SourceName, src.Config.Origin)
	} else if where := findKey(tree, chartConfigMarker, ""); where != "" {
		return nil, fmt.Errorf("refdoc: %s: the placeholder %s needs a configuration structure (Config.Root), found at %s", src.SourceName, chartConfigMarker, where)
	}
	if _, ok := tree.get("$comment"); ok {
		return nil, fmt.Errorf("refdoc: %s: the source must not set $comment, the generator writes it", src.SourceName)
	}
	if _, ok := tree.get("$schema"); ok {
		tree.insertAfter("$schema", "$comment", comment)
	} else {
		tree.insertAfter("", "$comment", comment)
	}
	var b bytes.Buffer
	if err := writeJSON(&b, tree, 0); err != nil {
		return nil, err
	}
	b.WriteByte('\n')
	return b.Bytes(), nil
}

// ------------------------------------------------------------ ordered JSON ---

// jsonObject is a JSON object that keeps the order of its keys.
type jsonObject struct {
	keys []string
	vals map[string]any
}

func newJSONObject() *jsonObject { return &jsonObject{vals: map[string]any{}} }

// set adds a key at the end, or replaces the value of an existing key in place.
func (o *jsonObject) set(key string, val any) {
	if _, ok := o.vals[key]; !ok {
		o.keys = append(o.keys, key)
	}
	o.vals[key] = val
}

func (o *jsonObject) get(key string) (any, bool) {
	v, ok := o.vals[key]
	return v, ok
}

// insertAfter adds a new key behind the key after (at the front when after is empty).
func (o *jsonObject) insertAfter(after, key string, val any) {
	at := 0
	for i, k := range o.keys {
		if k == after {
			at = i + 1
		}
	}
	o.keys = append(o.keys, "")
	copy(o.keys[at+1:], o.keys[at:])
	o.keys[at] = key
	o.vals[key] = val
}

// ---------------------------------------------------------------- the source ---

// parseSchemaSource reads the hand-written YAML into ordered JSON values. It accepts what a JSON document can say (mappings with
// string keys, lists, strings, booleans, numbers and null) and refuses the rest, with the line, instead of dropping it.
func parseSchemaSource(name string, data []byte) (*jsonObject, error) {
	dec := yaml.NewDecoder(bytes.NewReader(data))
	var doc yaml.Node
	if err := dec.Decode(&doc); err != nil {
		if errors.Is(err, io.EOF) {
			return nil, fmt.Errorf("refdoc: %s: the file is empty", name)
		}
		return nil, fmt.Errorf("refdoc: %s: %w", name, err)
	}
	var extra yaml.Node
	if err := dec.Decode(&extra); !errors.Is(err, io.EOF) {
		return nil, fmt.Errorf("refdoc: %s: the file must hold exactly one YAML document", name)
	}
	v, err := yamlValue(name, doc.Content[0])
	if err != nil {
		return nil, err
	}
	root, ok := v.(*jsonObject)
	if !ok {
		return nil, fmt.Errorf("refdoc: %s: the root of the schema must be a mapping", name)
	}
	return root, nil
}

func yamlValue(name string, n *yaml.Node) (any, error) {
	fail := func(format string, args ...any) (any, error) {
		return nil, fmt.Errorf("refdoc: %s:%d: %s", name, n.Line, fmt.Sprintf(format, args...))
	}
	if n.Kind == yaml.AliasNode || n.Anchor != "" {
		return fail("anchors and aliases are not supported: write the value out")
	}
	switch n.Kind {
	case yaml.MappingNode:
		obj := newJSONObject()
		for i := 0; i+1 < len(n.Content); i += 2 {
			k, v := n.Content[i], n.Content[i+1]
			if k.Kind != yaml.ScalarNode || k.Tag != "!!str" {
				return nil, fmt.Errorf("refdoc: %s:%d: a key must be a string (merge keys are not supported)", name, k.Line)
			}
			if _, dup := obj.get(k.Value); dup {
				return nil, fmt.Errorf("refdoc: %s:%d: the key %q is set twice", name, k.Line, k.Value)
			}
			val, err := yamlValue(name, v)
			if err != nil {
				return nil, err
			}
			obj.set(k.Value, val)
		}
		return obj, nil
	case yaml.SequenceNode:
		list := make([]any, 0, len(n.Content))
		for _, c := range n.Content {
			val, err := yamlValue(name, c)
			if err != nil {
				return nil, err
			}
			list = append(list, val)
		}
		return list, nil
	case yaml.ScalarNode:
		switch n.Tag {
		case "!!str":
			return n.Value, nil
		case "!!null":
			return nil, nil
		case "!!bool":
			var b bool
			if err := n.Decode(&b); err != nil {
				return fail("%q is not a boolean", n.Value)
			}
			return b, nil
		case "!!int":
			var i int64
			if err := n.Decode(&i); err != nil {
				return fail("%q is not an integer that fits 64 bits", n.Value)
			}
			return i, nil
		case "!!float":
			var f float64
			if err := n.Decode(&f); err != nil || math.IsInf(f, 0) || math.IsNaN(f) {
				return fail("%q is not a finite number", n.Value)
			}
			return f, nil
		}
		return fail("%q has the type %s, which a schema does not use: quote it to make it a string", n.Value, n.Tag)
	}
	return fail("unsupported YAML node")
}

// replaceConfigMarker puts the subtree where the source has the placeholder. The placeholder must be the only content of
// properties.config, and it must not appear anywhere else, so that a hand-written constraint beside it is never dropped silently.
func replaceConfigMarker(root *jsonObject, name, origin string, sub *jsonObject) error {
	props, _ := root.vals["properties"].(*jsonObject)
	if props == nil {
		return fmt.Errorf("refdoc: %s: the root has no properties", name)
	}
	marker, _ := props.vals["config"].(*jsonObject)
	if marker == nil || len(marker.keys) != 1 || marker.vals[chartConfigMarker] != origin {
		return fmt.Errorf("refdoc: %s: properties.config must consist of the placeholder %s: %s and nothing else", name, chartConfigMarker, origin)
	}
	props.set("config", sub)
	if where := findKey(root, chartConfigMarker, ""); where != "" {
		return fmt.Errorf("refdoc: %s: the placeholder %s must appear once, in properties.config; it also appears at %s", name, chartConfigMarker, where)
	}
	return nil
}

// findKey returns the JSON path of the first object that has the key, or "".
func findKey(v any, key, path string) string {
	switch x := v.(type) {
	case *jsonObject:
		if _, ok := x.vals[key]; ok {
			return path + "/" + key
		}
		for _, k := range x.keys {
			if where := findKey(x.vals[k], key, path+"/"+k); where != "" {
				return where
			}
		}
	case []any:
		for i, e := range x {
			if where := findKey(e, key, path+"/"+strconv.Itoa(i)); where != "" {
				return where
			}
		}
	}
	return ""
}

// ----------------------------------------------------------------- subtree ---

type chartSchemaGen struct {
	comments *configGen
	excluded map[string]bool
	used     map[string]bool
}

// subtree derives the schema of the configuration file from the structure: one property per YAML key, with the type of the field
// and the doc comment as the description. Every object is closed (additionalProperties false), so a key that the structure does
// not have is an error, as it is for the loader.
func (c ChartConfigSource) subtree() (*jsonObject, error) {
	if c.Root == nil || c.Root.Kind() != reflect.Struct {
		return nil, errors.New("refdoc: the root of the configuration subtree must be a struct type")
	}
	if strings.TrimSpace(c.Origin) == "" || strings.TrimSpace(c.Description) == "" {
		return nil, errors.New("refdoc: the configuration subtree needs an origin and a description")
	}
	doc, err := loadComments(c.SourceFiles)
	if err != nil {
		return nil, err
	}
	g := &chartSchemaGen{
		comments: &configGen{src: ConfigSource{SourceFiles: c.SourceFiles}, doc: doc},
		excluded: map[string]bool{},
		used:     map[string]bool{},
	}
	for _, e := range c.Excluded {
		if e.Path == "" || strings.TrimSpace(e.Reason) == "" {
			return nil, fmt.Errorf("refdoc: the exclusion %q needs a path and a reason", e.Path)
		}
		if g.excluded[e.Path] {
			return nil, fmt.Errorf("refdoc: the exclusion %q is listed twice", e.Path)
		}
		g.excluded[e.Path] = true
	}
	props, err := g.properties(c.Root, "")
	if err != nil {
		return nil, err
	}
	for _, e := range c.Excluded {
		if !g.used[e.Path] {
			return nil, fmt.Errorf("refdoc: the exclusion %q matches no setting of %s: remove it or correct the path", e.Path, c.Origin)
		}
	}
	desc, err := plainText(c.Description)
	if err != nil {
		return nil, err
	}
	if len(c.Excluded) > 0 {
		parts := make([]string, len(c.Excluded))
		for i, e := range c.Excluded {
			parts[i] = e.Path + " (" + strings.TrimSpace(e.Reason) + ")"
		}
		desc += " The chart does not offer these keys: " + strings.Join(parts, ", ") + "."
	}
	node := newJSONObject()
	node.set("type", "object")
	node.set("description", desc)
	node.set("additionalProperties", false)
	node.set("properties", props)
	return node, nil
}

// properties returns the properties of a struct type. prefix is the dotted path of the struct followed by a dot, or empty for
// the root.
func (g *chartSchemaGen) properties(t reflect.Type, prefix string) (*jsonObject, error) {
	props := newJSONObject()
	for i := 0; i < t.NumField(); i++ {
		sf := t.Field(i)
		key := configload.YAMLKey(sf)
		if !sf.IsExported() || key == "" {
			continue
		}
		path := prefix + key
		if g.excluded[path] {
			g.used[path] = true
			continue
		}
		node, err := g.typeNode(sf.Type, path)
		if err != nil {
			return nil, fmt.Errorf("refdoc: %s: %w", path, err)
		}
		text, name, err := g.comments.fieldText(t.Name(), sf, path)
		if err != nil {
			return nil, err
		}
		desc, err := plainText(leadingName(text, name, key))
		if err != nil {
			return nil, fmt.Errorf("refdoc: %s: %w", path, err)
		}
		props.set(key, withDescription(node, desc))
	}
	return props, nil
}

// typeNode returns the schema of a value of type t at path. It accepts the shapes that the configuration reference supports and
// refuses every other, so the two generators cannot disagree about what the structure may hold.
func (g *chartSchemaGen) typeNode(t reflect.Type, path string) (*jsonObject, error) {
	n := newJSONObject()
	if t == durationType {
		n.set("type", "string")
		n.set("pattern", durationPattern)
		return n, nil
	}
	switch t.Kind() {
	case reflect.String:
		n.set("type", "string")
	case reflect.Bool:
		n.set("type", "boolean")
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		n.set("type", "integer")
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		n.set("type", "integer")
		n.set("minimum", int64(0))
	case reflect.Float32, reflect.Float64:
		n.set("type", "number")
	case reflect.Struct:
		if t == timeType {
			return nil, errors.New("time.Time is not supported")
		}
		props, err := g.properties(t, path+".")
		if err != nil {
			return nil, err
		}
		n.set("type", "object")
		n.set("additionalProperties", false)
		n.set("properties", props)
	case reflect.Slice:
		if k := t.Elem().Kind(); k != reflect.String && k != reflect.Struct {
			return nil, fmt.Errorf("the type %s is not supported by the chart schema", t)
		}
		items, err := g.typeNode(t.Elem(), path+"[]")
		if err != nil {
			return nil, err
		}
		n.set("type", "array")
		n.set("items", items)
	case reflect.Map:
		e := t.Elem()
		listOfStrings := e.Kind() == reflect.Slice && e.Elem().Kind() == reflect.String
		if t.Key().Kind() != reflect.String || (e.Kind() != reflect.String && e.Kind() != reflect.Struct && !listOfStrings) {
			return nil, fmt.Errorf("the type %s is not supported by the chart schema", t)
		}
		vals, err := g.typeNode(e, path+".<name>")
		if err != nil {
			return nil, err
		}
		// An entry of a map is not nullable. Helm keeps a null for a key that values.yaml does not define, as it does for a map
		// entry, and the chart renders it into the configuration file, where the server refuses it when it starts. A null is no way
		// to switch off an entry of an earlier values file here: the entry is left out of the values. (The maps of the chart itself,
		// annotations and labels, are written by hand in the source, and they do take a null.)
		n.set("type", "object")
		n.set("additionalProperties", vals)
	default:
		return nil, fmt.Errorf("the type %s is not supported by the chart schema", t)
	}
	return n, nil
}

// withDescription returns a copy of the node with the description behind the type.
func withDescription(n *jsonObject, desc string) *jsonObject {
	out := newJSONObject()
	if t, ok := n.get("type"); ok {
		out.set("type", t)
	}
	out.set("description", desc)
	for _, k := range n.keys {
		if k != "type" {
			out.set(k, n.vals[k])
		}
	}
	return out
}

// plainText turns the text of a doc comment into one line for a description: the lines are joined with single spaces and a
// backtick must be paired. Unlike inline it escapes nothing, because a JSON string is not Markdown.
func plainText(text string) (string, error) {
	text = strings.Join(strings.Fields(text), " ")
	if strings.Count(text, "`")%2 != 0 {
		return "", fmt.Errorf("unpaired backtick in %q", text)
	}
	return text, nil
}

// ------------------------------------------------------------------ output ---

// writeJSON writes v with two spaces per level. Objects take one line per key; a list of scalars stays on one line while it is
// short, so the enumerations of the schema remain readable.
func writeJSON(b *bytes.Buffer, v any, level int) error {
	indent := func(l int) { b.WriteString(strings.Repeat("  ", l)) }
	switch x := v.(type) {
	case nil:
		b.WriteString("null")
	case bool:
		b.WriteString(strconv.FormatBool(x))
	case string:
		b.WriteString(quoteJSON(x))
	case int:
		b.WriteString(strconv.Itoa(x))
	case int64:
		b.WriteString(strconv.FormatInt(x, 10))
	case float64:
		b.WriteString(strconv.FormatFloat(x, 'f', -1, 64))
	case []any:
		if len(x) == 0 {
			b.WriteString("[]")
			return nil
		}
		if s, ok := inlineList(x); ok {
			b.WriteString(s)
			return nil
		}
		b.WriteString("[\n")
		for i, e := range x {
			indent(level + 1)
			if err := writeJSON(b, e, level+1); err != nil {
				return err
			}
			if i < len(x)-1 {
				b.WriteByte(',')
			}
			b.WriteByte('\n')
		}
		indent(level)
		b.WriteByte(']')
	case *jsonObject:
		if len(x.keys) == 0 {
			b.WriteString("{}")
			return nil
		}
		b.WriteString("{\n")
		for i, k := range x.keys {
			indent(level + 1)
			b.WriteString(quoteJSON(k) + ": ")
			if err := writeJSON(b, x.vals[k], level+1); err != nil {
				return err
			}
			if i < len(x.keys)-1 {
				b.WriteByte(',')
			}
			b.WriteByte('\n')
		}
		indent(level)
		b.WriteByte('}')
	default:
		return fmt.Errorf("refdoc: cannot write a value of type %T as JSON", v)
	}
	return nil
}

// inlineList renders a list of scalars on one line when the line is at most 80 characters long.
func inlineList(list []any) (string, bool) {
	parts := make([]string, len(list))
	for i, e := range list {
		var b bytes.Buffer
		switch e.(type) {
		case nil, bool, string, int, int64, float64:
			if err := writeJSON(&b, e, 0); err != nil {
				return "", false
			}
		default:
			return "", false
		}
		parts[i] = b.String()
	}
	s := "[" + strings.Join(parts, ", ") + "]"
	return s, len(s) <= 80
}

// quoteJSON quotes a string for JSON. Other than encoding/json it leaves <, > and & as they are (descriptions mention <name>)
// and escapes the two line separators that would break a JavaScript embedding.
func quoteJSON(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f || r == 0x2028 || r == 0x2029:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
