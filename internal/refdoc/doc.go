// Package refdoc renders the generated reference pages that are not part of the command line or REST API references: the server
// configuration (docs/reference/configuration.md), the environment variables (docs/reference/environment-variables.md) and the
// metrics (docs/reference/metrics.md). The pages come from the sources of truth, so they cannot drift:
//
//   - the configuration page from the configuration struct (internal/config) with its defaults and doc comments, and the loader
//     (internal/configload) for the environment overrides and the secret keys;
//   - the environment page from the loader, a registry of the other environment reads and the deployment templates;
//   - the metrics page from the metric definitions in the Go sources, found with go/ast.
//
// Only test files import this package, like internal/clidoc, so the generators never become part of a released binary. The
// pages are generated by "make docs-gen" (REFDOC_UPDATE=1 go test -run TestReferencePages ./internal/refdoc) and guarded against
// drift by the same test without the variable (internal/docgen writes and compares the files). The tests of this package also
// enforce the rules the generators rely on: doc comments on the configuration fields, a registry entry for every environment
// read and a literal form for every metric definition.
//
// Markdown from comments and help texts is escaped by one helper (see inline in markdown.go) because Hugo would drop text such
// as <base> as raw HTML.
